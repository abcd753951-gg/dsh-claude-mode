/**
 * Generate a reviewable cleanup script for DSH-owned temporary items.
 *
 * This is intentionally narrower than a general disk cleaner: it only touches
 * the two TEMP locations in the audit and only direct children whose name
 * starts with `dsh-` or `dsh_`. DSH's home, sessions, profiles, caches and
 * junctions are never candidates. The script is dry-run by default, checks that
 * DSH is stopped, and leaves any locked item in place.
 */

import { psQuote } from './data-plan.mjs'

const DEFAULT_DAYS = 7
const MIN_DAYS = 1
const MAX_DAYS = 365

export function normalizeOlderThanDays(value) {
  const days = value == null || value === '' ? DEFAULT_DAYS : Number(value)
  if (!Number.isFinite(days) || !Number.isInteger(days)) {
    throw new Error('olderThanDays must be an integer')
  }
  if (days < MIN_DAYS || days > MAX_DAYS) {
    throw new Error('olderThanDays must be between 1 and 365')
  }
  return days
}

/**
 * @param {{audit?: object, olderThanDays?: number, now?: number}} input
 */
export function buildCleanupPlan(input) {
  const audit = input && input.audit
  if (!audit || !audit.ok) throw new Error('audit result is required')
  const days = normalizeOlderThanDays(input && input.olderThanDays)
  const scopes = (Array.isArray(audit.categories) ? audit.categories : [])
    .filter((entry) => entry && entry.cleanable && entry.exists && entry.path)
    .map((entry) => ({
      id: entry.id,
      label: entry.label,
      path: entry.path,
      drive: entry.drive || '',
    }))
  if (scopes.length === 0) throw new Error('no cleanable temporary directory was found')

  const warnings = [
    '只处理临时目录中名称以 dsh- 或 dsh_ 开头的直接子项，不扫描也不删除 DSH 主目录、会话、附件与缓存。',
    '默认只列出候选，不会删除；确认列表后再加 -Apply。',
    '清理前必须完全退出 DSH；被其他进程占用的项目会保留。',
  ]
  const script = buildScript({ scopes, days })
  return {
    ok: true,
    olderThanDays: days,
    scopes,
    script,
    warnings,
    instructions: [
      '先完整退出 DSH（桌面端窗口关闭、CLI 全部退出）。',
      '把脚本保存为 .ps1，在普通 PowerShell（非 DSH 终端）里先运行：powershell -ExecutionPolicy Bypass -File .\\dsh-temp-cleanup.ps1',
      '检查打印出的候选路径、大小与时间；确认没有仍在使用的内容。',
      '确认后再运行：powershell -ExecutionPolicy Bypass -File .\\dsh-temp-cleanup.ps1 -Apply',
      '如要把临时目录固定到数据盘，请改用启动器设置 TEMP/TMP，不要给系统临时目录建 junction。',
    ],
  }
}

function buildScript({ scopes, days }) {
  const lines = []
  lines.push('# DeepSeek Harness temporary cleanup')
  lines.push('# Generated by dsh-claude-mode. Dry-run by default; add -Apply to delete.')
  lines.push('# Only direct dsh-* / dsh_* children of the TEMP locations below are candidates.')
  lines.push('# DSH home, sessions, profiles, attachments and caches are never touched.')
  lines.push('#requires -Version 5.1')
  lines.push('param(')
  lines.push('  [int]$Days = ' + days + ',')
  lines.push('  [switch]$Apply')
  lines.push(')')
  lines.push('$ErrorActionPreference = "Continue"')
  lines.push('if ($Days -lt ' + MIN_DAYS + ' -or $Days -gt ' + MAX_DAYS + ') { throw "Days must be between ' + MIN_DAYS + ' and ' + MAX_DAYS + '." }')
  lines.push('$running = Get-Process -Name "DeepSeek Harness" -ErrorAction SilentlyContinue')
  lines.push('if ($running) { throw "DSH 仍在运行。请先完整退出 DeepSeek Harness 再执行本脚本。" }')
  lines.push('$cutoff = (Get-Date).AddDays(-$Days)')
  lines.push('$scopes = @(')
  const scopeLines = scopes.map((scope) => '  @{ Id = ' + psQuote(scope.id) + '; Path = ' + psQuote(scope.path) + ' }')
  lines.push(scopeLines.join(',\n'))
  lines.push(')')
  lines.push('$total = 0')
  lines.push('$count = 0')
  lines.push('foreach ($scope in $scopes) {')
  lines.push('  if (-not (Test-Path -LiteralPath $scope.Path)) { Write-Host ("SKIP missing: " + $scope.Path); continue }')
  lines.push('  Write-Host ("SCOPE " + $scope.Id + ": " + $scope.Path)')
  lines.push('  $items = Get-ChildItem -LiteralPath $scope.Path -Force -ErrorAction SilentlyContinue |')
  lines.push('    Where-Object { $_.Name -match "^(dsh[-_])" -and $_.LastWriteTime -lt $cutoff }')
  lines.push('  foreach ($item in $items) {')
  lines.push('    if ($item.LinkType) { Write-Host ("SKIP reparse point: " + $item.FullName); continue }')
  lines.push('    $size = 0')
  lines.push('    if ($item.PSIsContainer) {')
  lines.push('      $size = (Get-ChildItem -LiteralPath $item.FullName -Recurse -File -Force -ErrorAction SilentlyContinue | Measure-Object -Property Length -Sum).Sum')
  lines.push('    } else { $size = $item.Length }')
  lines.push('    if ($null -eq $size) { $size = 0 }')
  lines.push('    $label = "{0,10:N1} MB  {1}" -f ($size / 1MB), $item.FullName')
  lines.push('    if ($Apply) {')
  lines.push('      try {')
  lines.push('        Remove-Item -LiteralPath $item.FullName -Recurse -Force -ErrorAction Stop')
  lines.push('        Write-Host ("REMOVED " + $label)')
  lines.push('        $total += $size')
  lines.push('        $count += 1')
  lines.push('      } catch {')
  lines.push('        Write-Host ("KEPT (in use or access denied): " + $item.FullName + " :: " + $_.Exception.Message)')
  lines.push('      }')
  lines.push('    } else {')
  lines.push('      Write-Host ("CANDIDATE " + $label)')
  lines.push('      $total += $size')
  lines.push('      $count += 1')
  lines.push('    }')
  lines.push('  }')
  lines.push('}')
  lines.push('if ($Apply) {')
  lines.push('  Write-Host ("Removed " + $count + " item(s), " + ("{0:N1}" -f ($total / 1MB)) + " MB.")')
  lines.push('} else {')
  lines.push('  Write-Host ("Dry run: " + $count + " candidate(s), " + ("{0:N1}" -f ($total / 1MB)) + " MB. Re-run with -Apply to delete.")')
  lines.push('}')
  lines.push('')
  lines.push('# This script intentionally never creates or changes a junction.')
  return lines.join('\n')
}
