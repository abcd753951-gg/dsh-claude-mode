/**
 * Generate a reviewable, external migration script for the data locations the
 * audit found. The plugin never runs this script: DSH must be stopped first and
 * the user keeps a parked copy of every moved directory until verification.
 */

import path from 'node:path'

const ROOT_TARGETS = Object.freeze({
  'harness-home': 'harness-home',
  'desktop-profile': 'desktop-profile',
  'updater-cache': 'updater-cache',
  'pnpm-store': 'pnpm-store',
  'pnpm-cache': 'pnpm-cache',
  'npm-cache': 'npm-cache',
})

/** Quote one PowerShell single-quoted literal. */
export function psQuote(value) {
  return "'" + String(value == null ? '' : value).replace(/'/g, "''") + "'"
}

function isInside(child, parent) {
  const relative = path.relative(parent, child)
  return relative === '' || (!relative.startsWith('..') && !path.isAbsolute(relative))
}

/** Validate a migration root; returns a normalized absolute path or throws. */
export function normalizeTargetRoot(value) {
  const raw = String(value == null ? '' : value).trim()
  if (!raw) throw new Error('target root is required')
  if (!path.isAbsolute(raw)) throw new Error('target root must be an absolute path')
  if (raw.length > 180) throw new Error('target root is too long')
  const normalized = path.resolve(raw)
  if (normalized === path.parse(normalized).root) throw new Error('target root cannot be a drive root')
  return normalized
}

/**
 * Build the migration plan from an audit result. Every destructive step is
 * gated by a target-not-exists check; already managed junctions are skipped.
 *
 * @param {{targetRoot: string, audit: object, now?: number}} input
 */
export function buildMigrationPlan(input) {
  const targetRoot = normalizeTargetRoot(input && input.targetRoot)
  const audit = input && input.audit && input.audit.ok ? input.audit : null
  if (!audit) throw new Error('audit result is required')
  const actions = []
  const skipped = []
  const warnings = []
  const categories = Array.isArray(audit.categories) ? audit.categories : []
  for (const category of categories) {
    const targetName = ROOT_TARGETS[category.id]
    if (!targetName) {
      skipped.push({ id: category.id, reason: 'not-migratable' })
      continue
    }
    if (category.migrate === false) {
      skipped.push({ id: category.id, reason: 'not-migratable' })
      continue
    }
    if (!category.exists) {
      skipped.push({ id: category.id, reason: 'missing' })
      continue
    }
    if (category.managed) {
      skipped.push({ id: category.id, reason: 'already-managed' })
      continue
    }
    const target = path.join(targetRoot, targetName)
    if (isInside(targetRoot, category.path) || isInside(category.path, targetRoot)) {
      throw new Error('target root overlaps a source directory')
    }
    actions.push({
      id: category.id,
      label: category.label,
      source: category.path,
      target,
      bytes: Number(category.bytes) || 0,
      approx: Boolean(category.approx),
      drive: category.drive || '',
      targetDrive: path.parse(target).root,
    })
  }
  if (actions.length === 0) {
    warnings.push('没有需要迁移的直写目录：已有目录要么已托管，要么不存在。')
  }
  const temp = categories.filter((entry) => entry.id === 'temp' || entry.id === 'system-temp').find((entry) => entry.exists)
  if (temp) {
    warnings.push('临时目录不通过 junction 迁移：请用「生成清理脚本」清理旧的 dsh-* 临时项，或在启动器里设置 TEMP/TMP。')
  }
  if (audit.unmanagedBytes > 0) {
    const approximate = categories.some((entry) => entry.exists && !entry.managed && entry.approx)
    warnings.push('未托管目录合计 ' + (approximate ? '至少 ' : '') + formatCompactBytes(audit.unmanagedBytes) + '；脚本只处理下方列出的目录。')
  }
  const script = buildScript({
    targetRoot,
    actions,
    skipped,
    generatedAt: input && input.now ? new Date(input.now) : new Date(),
  })
  return {
    ok: true,
    targetRoot,
    actions,
    skipped,
    warnings,
    script,
    instructions: [
      '先完整退出 DSH（桌面端窗口关闭、CLI 全部退出），确认任务管理器里没有 DeepSeek Harness 进程。',
      '把脚本保存为 .ps1，在普通 PowerShell（非 DSH 终端）里执行；脚本发现 DSH 仍在运行会直接退出。',
      '脚本复制并校验通过后，把原目录重命名为 *.data-keeper-<时间戳>，再建立 junction；不会自动删除旧副本。',
      '验证迁移后，确认旧副本无误再手动删除；如需回滚，先删除 junction，再把旧副本改回原名。',
      '临时目录不要建 junction；用下方的清理脚本处理旧 dsh-* 临时项，或由启动器设置 TEMP/TMP。',
    ],
  }
}

function formatCompactBytes(value) {
  const bytes = Math.max(0, Number(value) || 0)
  if (bytes < 1024) return bytes + ' B'
  const units = ['KB', 'MB', 'GB', 'TB']
  let amount = bytes
  let unit = 'B'
  for (const next of units) {
    amount /= 1024
    unit = next
    if (amount < 1024) break
  }
  return (amount >= 10 ? amount.toFixed(1) : amount.toFixed(2)) + ' ' + unit
}

function buildScript({ targetRoot, actions, skipped, generatedAt }) {
  const lines = []
  lines.push('# DeepSeek Harness data migration')
  lines.push('# Generated by dsh-claude-mode · ' + generatedAt.toISOString())
  lines.push('# Review this file before running. DSH must be completely stopped.')
  lines.push('#requires -Version 5.1')
  lines.push('$ErrorActionPreference = "Stop"')
  lines.push('$root = ' + psQuote(targetRoot))
  lines.push('$stamp = Get-Date -Format "yyyyMMdd-HHmmss"')
  lines.push('$log = Join-Path $root ("data-keeper-" + $stamp + ".log")')
  lines.push('New-Item -ItemType Directory -Path $root -Force | Out-Null')
  lines.push('function Write-Log([string]$message) { $line = (Get-Date -Format s) + " " + $message; Write-Host $line; Add-Content -LiteralPath $log -Value $line -Encoding UTF8 }')
  lines.push('$running = Get-Process -Name "DeepSeek Harness" -ErrorAction SilentlyContinue')
  lines.push('if ($running) { throw "DSH 仍在运行。请先完整退出 DeepSeek Harness 再执行本脚本。" }')
  lines.push('Write-Log "Migration started: " + $root')
  lines.push('$items = @(')
  const itemLines = actions.map((action) => '  @{ Id = ' + psQuote(action.id) + '; Source = ' + psQuote(action.source) + '; Target = ' + psQuote(action.target) + ' }')
  lines.push(itemLines.join(',\n'))
  lines.push(')')
  lines.push('foreach ($item in $items) {')
  lines.push('  $source = [string]$item.Source')
  lines.push('  $target = [string]$item.Target')
  lines.push('  if (-not (Test-Path -LiteralPath $source)) { Write-Log ("SKIP missing: " + $source); continue }')
  lines.push('  $sourceItem = Get-Item -LiteralPath $source -Force')
  lines.push('  if ($sourceItem.LinkType -eq "Junction") { Write-Log ("SKIP already managed: " + $source); continue }')
  lines.push('  if (Test-Path -LiteralPath $target) { throw ("Refusing to overwrite existing target: " + $target) }')
  lines.push('  New-Item -ItemType Directory -Path (Split-Path -Parent $target) -Force | Out-Null')
  lines.push('  $copyLog = Join-Path $root ("robocopy-" + $item.Id + "-" + $stamp + ".log")')
  lines.push('  Write-Log ("COPY " + $source + " -> " + $target)')
  lines.push('  & robocopy $source $target /E /COPY:DAT /DCOPY:DAT /R:1 /W:1 /NP /NFL /NDL /NJH /UNILOG:$copyLog')
  lines.push('  if ($LASTEXITCODE -ge 8) { throw ("robocopy failed for " + $source + " (exit " + $LASTEXITCODE + ")") }')
  lines.push('  $sourceBytes = (Get-ChildItem -LiteralPath $source -Recurse -File -Force -ErrorAction Stop | Measure-Object -Property Length -Sum).Sum')
  lines.push('  $targetBytes = (Get-ChildItem -LiteralPath $target -Recurse -File -Force -ErrorAction Stop | Measure-Object -Property Length -Sum).Sum')
  lines.push('  if ($null -eq $sourceBytes) { $sourceBytes = 0 }')
  lines.push('  if ($null -eq $targetBytes) { $targetBytes = 0 }')
  lines.push('  if ($sourceBytes -ne $targetBytes) { throw ("size verification failed for " + $source + ": " + $sourceBytes + " != " + $targetBytes) }')
  lines.push('  $parked = $source + ".data-keeper-" + $stamp')
  lines.push('  if (Test-Path -LiteralPath $parked) { throw ("parked path already exists: " + $parked) }')
  lines.push('  Rename-Item -LiteralPath $source -NewName (Split-Path -Leaf $parked)')
  lines.push('  try {')
  lines.push('    New-Item -ItemType Junction -Path $source -Target $target | Out-Null')
  lines.push('    $link = Get-Item -LiteralPath $source -Force')
  lines.push('    if ($link.LinkType -ne "Junction" -or -not ($link.Target -contains $target)) { throw "junction verification failed" }')
  lines.push('    Write-Log ("OK " + $source + " -> " + $target + "; parked=" + $parked)')
  lines.push('  } catch {')
  lines.push('    if (Test-Path -LiteralPath $source) { Remove-Item -LiteralPath $source -Force -Recurse -ErrorAction SilentlyContinue }')
  lines.push('    if (Test-Path -LiteralPath $parked) { Rename-Item -LiteralPath $parked -NewName (Split-Path -Leaf $source) }')
  lines.push('    throw')
  lines.push('  }')
  lines.push('}')
  lines.push('Write-Log "Migration complete. Review parked directories before deleting them."')
  lines.push('Write-Log ("Log: " + $log)')
  lines.push('')
  lines.push('# Skipped by the plan:')
  for (const skip of skipped) lines.push('# - ' + skip.id + ': ' + skip.reason)
  lines.push('')
  lines.push('# Rollback for one item:')
  lines.push('#   Remove-Item -LiteralPath "<source>" -Force')
  lines.push('#   Rename-Item -LiteralPath "<source>.data-keeper-<stamp>" -NewName "<leaf>"')
  lines.push('')
  lines.push('# TEMP/TMP are intentionally not junctioned; set them in the launcher, for example:')
  lines.push('#   $env:TEMP = "E:\\DeepSeek-Harness-Data\\temp"; $env:TMP = $env:TEMP')
  return lines.join('\n')
}
